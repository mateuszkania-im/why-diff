#!/usr/bin/env node
/**
 * Builds the standalone CLI: one ESM file, zero runtime dependencies,
 * committed at plugin/bin/why-diff.mjs. It is what `npx github:...` runs,
 * what the Claude Code plugin hook runs (no network, no install), and what
 * the GitHub Action runs.
 *
 *   node scripts/build.mjs          build
 *   node scripts/build.mjs --check  fail if the committed file is stale (CI)
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'plugin', 'bin', 'why-diff.mjs');
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

const result = await build({
  entryPoints: [path.join(root, 'src', 'cli.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  minifySyntax: true,
  minifyWhitespace: false,
  legalComments: 'none',
  define: { __WHY_DIFF_VERSION__: JSON.stringify(pkg.version) },
  // commander is CommonJS and requires node builtins; give the ESM bundle a require().
  banner: { js: "import { createRequire as __whyDiffCreateRequire } from 'node:module';\nconst require = __whyDiffCreateRequire(import.meta.url);" },
});

let code = result.outputFiles[0].text;
code = code.replace(/^#!.*\n/, '');
code = `#!/usr/bin/env node\n// why-diff ${pkg.version} (standalone build, generated by scripts/build.mjs; do not edit)\n${code}`;

if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== code) {
    console.error('plugin/bin/why-diff.mjs is stale: run `npm run build` and commit it.');
    process.exit(1);
  }
  console.log('plugin/bin/why-diff.mjs is up to date');
} else {
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, code, { mode: 0o755 });
  console.log(`wrote ${path.relative(root, out)} (${(code.length / 1024).toFixed(0)} KB)`);
}
